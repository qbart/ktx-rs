def body_of(cname):
    m = re.search(r"\b" + re.escape(cname) + r"\s*(\[[^\]]*\])+\s*=\s*\{", cpp)
    assert m, cname
    i = m.end() - 1
    depth = 0
    for j in range(i, len(cpp)):
        if cpp[j] == "{":
            depth += 1
        elif cpp[j] == "}":
            depth -= 1
            if depth == 0:
                return cpp[i + 1 : j]
    raise AssertionError(cname)


def tokens(body):
    body = re.sub(r"//[^\n]*", "", body)
    return re.findall(r"0x[0-9a-fA-F]+|-?\d+|true|false", body)


def lit(t, ty):
    if t in ("true", "false"):
        return t
    v = int(t, 0)
    if ty == "bool":
        return "true" if v else "false"
    return str(v)


out = ["// Generated by scripts/gen_uastc_tables.py from basisu_transcoder.cpp. Do not edit.", ""]
for rust, cname, ty, shape in TABLES:
    body = body_of(cname)
    if shape is None:
        vals = tokens(body)
        out.append(f"pub const {rust}: [{ty}; {len(vals)}] = [{', '.join(vals)}];")
    elif shape < 0:
        # inner groups padded to |shape| with zeros (C zero-init)
        groups = re.findall(r"\{([^{}]*)\}", body)
        rows = []
        for g in groups:
            v = tokens(g)
            v += ["0"] * (-shape - len(v))
            rows.append("[" + ", ".join(v) + "]")
        out.append(f"pub const {rust}: [{ty}; {len(rows)}] = [{', '.join(rows)}];")
    else:
        groups = re.findall(r"\{([^{}]*)\}", body)
        if not groups:
            vals = tokens(body)
            groups = [" ".join(vals[k : k + shape]) for k in range(0, len(vals), shape)]
        rows = []
        tys = ty.strip("()").split(", ") if ty.startswith("(") else None
        for g in groups:
            v = tokens(g)
            assert len(v) == shape, (rust, g)
            if tys:
                rows.append("(" + ", ".join(lit(x, t) for x, t in zip(v, tys)) + ")")
            else:
                rows.append("[" + ", ".join(v) + "]")
        out.append(f"pub const {rust}: [{ty}; {len(rows)}] = [{', '.join(rows)}];")
    out.append("")

Path("src/basisu/uastc_tables.rs").write_text("\n".join(out))
print("wrote src/basisu/uastc_tables.rs")
