#!/usr/bin/env python3
"""Generate src/vkformat/generated.rs from the reference KTX-Software sources.

Usage: python3 scripts/gen_vkformat.py [ref_dir]
Sources: lib/src/vkformat_enum.h, vkformat_str.c, vkformat_check.c,
vkformat_check_variant.c, vkformat_typesize.c.
"""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx") / "lib" / "src"
out = Path("src/vkformat/generated.rs")


def strip(name):
    return name[len("VK_FORMAT_"):]


def body_of(text, func):
    m = re.search(r"\n" + func + r"\(VkFormat format\)\n\{(.*?)\n\}\n", text, re.S)
    if not m:
        sys.exit(f"function {func} not found")
    return m.group(1)


enum_src = (ref / "vkformat_enum.h").read_text()
enum_body = re.search(r"typedef enum VkFormat \{(.*?)\} VkFormat;", enum_src, re.S).group(1)
entries = []
for m in re.finditer(r"(VK_FORMAT_\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", enum_body):
    name, val = m.group(1), m.group(2)
    if name == "VK_FORMAT_MAX_ENUM":
        continue
    entries.append((strip(name), int(val, 0)))
max_std = int(re.search(r"#define VK_FORMAT_MAX_STANDARD_ENUM (\d+)", enum_src).group(1))

check_src = (ref / "vkformat_check.c").read_text()
variant_src = (ref / "vkformat_check_variant.c").read_text()


def bool_cases(text, func):
    return [strip(c) for c in re.findall(r"case (VK_FORMAT_\w+):", body_of(text, func))]


prohibited = bool_cases(check_src, "isProhibitedFormat")
srgb = bool_cases(check_src, "isSrgbFormat")
valid_extra = bool_cases(check_src, "isValidFormat")
srgb_variant = bool_cases(variant_src, "isNotSrgbFormatButHasSrgbVariant")

size_src = body_of((ref / "vkformat_typesize.c").read_text(), "vkFormatTypeSize")
type_sizes = [(strip(n), int(v)) for n, v in re.findall(r"case (VK_FORMAT_\w+):\s*return (\d+);", size_src)]

str_src = (ref / "vkformat_str.c").read_text()
names = [(strip(n), s) for n, s in re.findall(r'case (VK_FORMAT_\w+):\s*return "(\w+)";', body_of(str_src, "vkFormatString"))]
parse_body = re.search(r"stringToVkFormat\(const char\* str\)\n\{(.*?)\n\}\n", str_src, re.S).group(1)
parses = [(s, strip(n)) for s, n in re.findall(r'ktx_strcasecmp\(str, "(\w+)"\) == 0\)\s*return (VK_FORMAT_\w+);', parse_body)]

L = []
w = L.append
w("// @generated by scripts/gen_vkformat.py from KTX-Software lib/src/vkformat_*.{h,c}. Do not edit.")
w("#![allow(non_upper_case_globals)]")
w("")
w("use super::VkFormat;")
w("")
w(f"/// Port of `VK_FORMAT_MAX_STANDARD_ENUM`.")
w(f"pub const VK_FORMAT_MAX_STANDARD_ENUM: u32 = {max_std};")
w("")
w("impl VkFormat {")
for n, v in entries:
    w(f"    pub const {n}: VkFormat = VkFormat({v});")
w("    /// Port of `VK_FORMAT_MAX_ENUM`.")
w("    pub const MAX_ENUM: VkFormat = VkFormat(0x7FFFFFFF);")
w("}")
w("")
w("/// All enumerants in declaration order (name without `VK_FORMAT_` prefix, value).")
w("pub const VK_FORMAT_ENTRIES: &[(&str, VkFormat)] = &[")
for n, v in entries:
    w(f'    ("{n}", VkFormat::{n}),')
w("];")
w("")


def matcher(fn, doc, cases, extra_pre=None):
    w(f"/// {doc}")
    w(f"pub fn {fn}(format: VkFormat) -> bool {{")
    if extra_pre:
        w(f"    {extra_pre}")
    w("    matches!(")
    w("        format,")
    for i, c in enumerate(cases):
        sep = "" if i == len(cases) - 1 else " |"
        w(f"        VkFormat::{c}{sep}")
    w("    )")
    w("}")
    w("")


matcher("is_prohibited_format", "Port of `isProhibitedFormat`.", prohibited)
matcher("is_srgb_format", "Port of `isSrgbFormat`.", srgb)
matcher("is_valid_format", "Port of `isValidFormat`.", valid_extra,
        "if format.0 <= VK_FORMAT_MAX_STANDARD_ENUM {\n        return true;\n    }")
matcher("is_not_srgb_format_but_has_srgb_variant", "Port of `isNotSrgbFormatButHasSrgbVariant`.", srgb_variant)

w("/// Port of `vkFormatTypeSize`.")
w("pub fn vk_format_type_size(format: VkFormat) -> u32 {")
w("    match format {")
for n, v in type_sizes:
    w(f"        VkFormat::{n} => {v},")
w("        _ => 0,")
w("    }")
w("}")
w("")
w("/// Port of `vkFormatString`.")
w("pub fn vk_format_string(format: VkFormat) -> &'static str {")
w("    match format {")
for n, s in names:
    w(f'        VkFormat::{n} => "{s}",')
w('        _ => "VK_UNKNOWN_FORMAT",')
w("    }")
w("}")
w("")
w("/// Name table used by `string_to_vk_format` (without `VK_FORMAT_` prefix).")
w("pub(super) const VK_FORMAT_PARSE_TABLE: &[(&str, VkFormat)] = &[")
for s, n in parses:
    w(f'    ("{s}", VkFormat::{n}),')
w("];")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L) + "\n")
print(f"wrote {out}: {len(entries)} enums, {len(parses)} parse names")

# Test fixture: tests/unittests/vkformat_list.inl -> tests/common/vkformat_list.rs
lst = (ref.parent.parent / "tests/unittests/vkformat_list.inl").read_text()
names = re.findall(r"^(VK_FORMAT_\w+),", lst, re.M)
tout = Path("tests/common/vkformat_list.rs")
tout.parent.mkdir(parents=True, exist_ok=True)
tout.write_text(
    "// @generated by scripts/gen_vkformat.py from tests/unittests/vkformat_list.inl. Do not edit.\n"
    "use ktx::VkFormat;\n\n/// Port of `vkformat_list.inl`.\npub const FORMATS: &[VkFormat] = &[\n"
    + "".join(f"    VkFormat::{strip(n)},\n" for n in names) + "];\n")
print(f"wrote {tout}: {len(names)} formats")
