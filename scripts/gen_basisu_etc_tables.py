#!/usr/bin/env python3
"""Generates src/basisu/etc_enc_tables.rs from external/basis_universal/encoder/basisu_etc.cpp
in ./ref/ktx: ETC1 color8 -> block config tables, cluster fit order table and the
evaluate distance tables."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "ktx", "external", "basis_universal", "encoder", "basisu_etc.cpp")
OUT = os.path.join(ROOT, "src", "basisu", "etc_enc_tables.rs")

with open(SRC) as f:
    text = f.read()
text = re.sub(r"//[^\n]*", "", text)
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def body(start):
    i = text.index("{", text.index(start))
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    raise ValueError(start)


def groups(t):
    out, depth, start = [], 0, None
    for j, c in enumerate(t):
        if c == "{":
            if depth == 0:
                start = j + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(t[start:j])
    return out


def ints(t):
    return [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", t)]


def rows(name, width, hexfmt=False):
    out = []
    for g in groups(body(name)):
        v = ints(g)
        assert len(v) <= width, (name, len(v))
        v += [0] * (width - len(v))
        f = (lambda x: "0x%04X" % x) if hexfmt else str
        out.append("    [" + ", ".join(f(x) for x in v) + "],")
    return out


c0 = rows("g_etc1_color8_to_etc_block_config_0_255[2][33]", 33, True)
c1 = rows("g_etc1_color8_to_etc_block_config_1_to_254[254][12]", 12, True)
cf = [ints(g) for g in groups(body("g_cluster_fit_order_tab[BASISU_ETC1_CLUSTER_FIT_ORDER_TABLE_SIZE]"))]
ed = rows("g_eval_dist_tables[8][256]", 256)
assert len(c0) == 2 and len(c1) == 254 and len(cf) == 165 and len(ed) == 8

with open(OUT, "w") as f:
    f.write("//! Generated by `scripts/gen_basisu_etc_tables.py` from `encoder/basisu_etc.cpp`. Do not edit.\n\n")
    f.write("/// `g_etc1_color8_to_etc_block_config_0_255`.\n")
    f.write("pub static ETC1_COLOR8_TO_ETC_BLOCK_CONFIG_0_255: [[u16; 33]; 2] = [\n" + "\n".join(c0) + "\n];\n\n")
    f.write("/// `g_etc1_color8_to_etc_block_config_1_to_254` (rows end with 0xFFFF, zero padded).\n")
    f.write("pub static ETC1_COLOR8_TO_ETC_BLOCK_CONFIG_1_TO_254: [[u16; 12]; 254] = [\n" + "\n".join(c1) + "\n];\n\n")
    f.write("/// `g_cluster_fit_order_tab`.\n")
    f.write("pub static CLUSTER_FIT_ORDER_TAB: [[u8; 4]; 165] = [\n")
    for i in range(0, 165, 8):
        f.write("    " + " ".join("[%s]," % ", ".join(map(str, v)) for v in cf[i:i + 8]) + "\n")
    f.write("];\n\n")
    f.write("/// `g_eval_dist_tables`.\n")
    f.write("pub static EVAL_DIST_TABLES: [[u8; 256]; 8] = [\n" + "\n".join(ed) + "\n];\n")
