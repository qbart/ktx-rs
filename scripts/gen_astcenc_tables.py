#!/usr/bin/env python3
"""Generates src/astcenc/tables.rs from the astc-encoder sources in ./ref/ktx
(external/astc-encoder/Source): integer sequence trit/quint tables, weight
unquantization maps, color unquantization maps and the color quant mode table."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "ktx", "external", "astc-encoder", "Source")


def read(name):
    with open(os.path.join(SRC, name)) as f:
        text = f.read()
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def body(text, start):
    """Text inside the outermost braces after `start`."""
    i = text.index("{", text.index(start))
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    raise ValueError(start)


def ints(text):
    return [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", text.replace("_", "0"))]


def groups(text):
    """Top-level brace groups of a body."""
    out, depth, start = [], 0, None
    for j, c in enumerate(text):
        if c == "{":
            if depth == 0:
                start = j + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(text[start:j])
    return out


def fmt(values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


ise = read("astcenc_integer_sequence.cpp")
quints = ints(body(ise, "quints_of_integer[128][3]"))
trits = ints(body(ise, "trits_of_integer[256][5]"))
assert len(quints) == 384 and len(trits) == 1280

xfer = read("astcenc_weight_quant_xfer_tables.cpp")
weight_maps = []
for entry in groups(body(xfer, "quant_and_xfer_tables[12]")):
    parts = groups(entry)
    m = ints(parts[2])
    weight_maps.append(m + [0] * (32 - len(m)))
assert len(weight_maps) == 12

quant = read("astcenc_quantization.cpp")
levels = [6, 8, 10, 12, 16, 20, 24, 32, 40, 48, 64, 80, 96, 128, 160, 192, 256]
color_maps = []
for q in levels:
    v = ints(body(quant, f"color_scrambled_pquant_to_uquant_q{q}[{q}]"))
    assert len(v) == q, q
    color_maps.append(v)
qmt = ints(body(quant, "quant_mode_table[10][128]"))
assert len(qmt) == 1280

out = ["//! Generated by scripts/gen_astcenc_tables.py from astc-encoder; do not edit.", ""]
out.append("/// `quints_of_integer[128][3]`.")
out.append("pub const QUINTS_OF_INTEGER: [[u8; 3]; 128] = [")
out += [f"    [{', '.join(map(str, quints[i:i + 3]))}]," for i in range(0, 384, 3)]
out.append("];")
out.append("/// `trits_of_integer[256][5]`.")
out.append("pub const TRITS_OF_INTEGER: [[u8; 5]; 256] = [")
out += [f"    [{', '.join(map(str, trits[i:i + 5]))}]," for i in range(0, 1280, 5)]
out.append("];")
out.append("/// `quant_and_xfer_tables[q].unscramble_and_unquant_map`.")
out.append("pub const WEIGHT_UNSCRAMBLE_AND_UNQUANT: [[u8; 32]; 12] = [")
out += [f"    [{', '.join(map(str, m))}]," for m in weight_maps]
out.append("];")
for q, m in zip(levels, color_maps):
    out.append(f"const COLOR_Q{q}: [u8; {q}] = [")
    out.append(fmt(m))
    out.append("];")
out.append("/// `color_scrambled_pquant_to_uquant_tables` (from QUANT_6).")
out.append("pub const COLOR_SCRAMBLED_PQUANT_TO_UQUANT: [&[u8]; 17] = [")
out.append("    " + ", ".join(f"&COLOR_Q{q}" for q in levels) + ",")
out.append("];")
out.append("/// `quant_mode_table[integer_count / 2][bits]`.")
out.append("pub const QUANT_MODE_TABLE: [[i8; 128]; 10] = [")
for i in range(10):
    out.append("    [")
    out.append(fmt(qmt[i * 128:(i + 1) * 128]).replace("    ", "        "))
    out.append("    ],")
out.append("];")
path = os.path.join(ROOT, "src", "astcenc", "tables.rs")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", path)
