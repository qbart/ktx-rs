#!/usr/bin/env python3
"""Generate src/basisu/tables.rs from Basis Universal transcoder tables.

Sources are the *.inc files and selected inline arrays of basisu_transcoder.cpp.
Each table becomes a `pub static NAME: [(T0, T1, ...); N]`.
"""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx") / "external/basis_universal/transcoder"
cpp = (ref / "basisu_transcoder.cpp").read_text()

# (rust name, source, types)
INC = [
    ("ETC1_TO_DXT_6", "basisu_transcoder_tables_dxt1_6.inc", ("u8", "u8", "u16")),
    ("ETC1_TO_DXT_5", "basisu_transcoder_tables_dxt1_5.inc", ("u8", "u8", "u16")),
    ("ETC1_TO_BC7_M5_COLOR", "basisu_transcoder_tables_bc7_m5_color.inc", ("u8", "u8", "u16")),
    ("ETC1_G_TO_BC7_M5A", "basisu_transcoder_tables_bc7_m5_alpha.inc", ("u8", "u8", "u8")),
    ("ETC1_TO_ASTC", "basisu_transcoder_tables_astc.inc", ("u8", "u8", "u16")),
    ("ETC1_TO_ASTC_0_255", "basisu_transcoder_tables_astc_0_255.inc", ("u8", "u8", "u16")),
    ("ETC1S_TO_PVRTC2_45", "basisu_transcoder_tables_pvrtc2_45.inc", ("u8", "u8", "u16")),
    ("ETC1S_TO_ATC_55", "basisu_transcoder_tables_atc_55.inc", ("u8", "u8", "u16")),
    ("ETC1S_TO_ATC_56", "basisu_transcoder_tables_atc_56.inc", ("u8", "u8", "u16")),
]
# inline arrays in basisu_transcoder.cpp: (rust name, C array name, types)
INLINE = [
    ("ETC1_G_TO_DXT5A", "g_etc1_g_to_dxt5a", ("u8", "u8", "u16")),
    ("ETC1_G_TO_ETC2_A8", "s_etc1_g_to_etc2_a8", ("u8", "u8", "u16")),
    ("BC7_M5_EQUALS_1", "g_bc7_m5_equals_1", ("u8", "u8")),
    ("ETC1_G_TO_ETC2_R11", "s_etc1_g_to_etc2_r11", ("u8", "u8", "u16")),
]


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def tuples(text, n):
    out = []
    for m in re.finditer(r"\{\s*([-\d\s,]+?)\s*\}", text):
        vals = [int(v) for v in m.group(1).split(",") if v.strip()]
        if len(vals) == n:
            out.append(vals)
    return out


def inline_body(name):
    m = re.search(re.escape(name) + r"\s*\[[^=]*=\s*\{", cpp)
    if not m:
        sys.exit(f"inline table {name} not found")
    i = m.end() - 1
    depth = 0
    for j in range(i, len(cpp)):
        if cpp[j] == "{":
            depth += 1
        elif cpp[j] == "}":
            depth -= 1
            if depth == 0:
                return cpp[i + 1:j]
    sys.exit("unbalanced")


L = ["// @generated by scripts/gen_basisu_tables.py from basis_universal/transcoder. Do not edit.",
     "//! Basis Universal transcoder lookup tables.", "#![allow(clippy::unreadable_literal)]", ""]


def emit(name, rows, types):
    ty = "(" + ", ".join(types) + ")"
    L.append(f"pub static {name}: [{ty}; {len(rows)}] = [")
    line = []
    for r in rows:
        line.append("(" + ",".join(str(v) for v in r) + ")")
        if len(line) == 16:
            L.append("    " + ", ".join(line) + ",")
            line = []
    if line:
        L.append("    " + ", ".join(line) + ",")
    L.append("];")
    L.append("")


for name, f, types in INC:
    rows = tuples(strip_comments((ref / f).read_text()), len(types))
    emit(name, rows, types)
for name, cname, types in INLINE:
    rows = tuples(strip_comments(inline_body(cname)), len(types))
    emit(name, rows, types)

Path("src/basisu/tables.rs").write_text("\n".join(L) + "\n")
print("wrote src/basisu/tables.rs")
