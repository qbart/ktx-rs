#!/usr/bin/env python3
"""Generates src/astcenc/percentile_tables.rs from astcenc_percentile_tables.cpp in
./ref/ktx/external/astc-encoder/Source (the packed 2D block mode percentile tables)."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "ktx", "external", "astc-encoder", "Source", "astcenc_percentile_tables.cpp")

text = open(SRC).read()
text = re.sub(r"//[^\n]*", "", text)
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)

arrays = {}
for m in re.finditer(r"static const uint16_t (percentile_arr_\w+)\[(\d+)\]\s*\{([^}]*)\}", text):
    vals = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", m.group(3))]
    assert len(vals) == int(m.group(2)), m.group(1)
    arrays[m.group(1)] = vals

tables = []
for m in re.finditer(r"static const packed_percentile_table (block_pcd_\w+)\s*=?\s*\{(.*?)\};", text, re.S):
    body = m.group(2)
    nums = [int(v) for v in re.findall(r"\b\d+\b", re.sub(r"percentile_arr_\w+", "", body))]
    names = re.findall(r"percentile_arr_\w+", body)
    dim_x, dim_y, c0, c1, d0, d1, i0, i1 = nums
    tables.append((m.group(1), dim_x, dim_y, (c0, c1), (d0, d1), (i0, i1), names))

out = ["//! Generated by scripts/gen_astcenc_percentile.py from astcenc_percentile_tables.cpp.",
       "//! Do not edit.", "", "#![allow(clippy::unreadable_literal)]", "",
       "/// Port of `packed_percentile_table`.",
       "pub struct PackedPercentileTable {",
       "    pub dim_x: u8,", "    pub dim_y: u8,", "    pub item_count: [u16; 2],",
       "    pub difscales: [u16; 2],", "    pub initial_percs: [u16; 2],",
       "    pub items: [&'static [u16]; 2],", "}", ""]
for name, vals in arrays.items():
    out.append(f"static {name.upper()}: [u16; {len(vals)}] = [")
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(f"0x{v:04X}" for v in vals[i:i + 12]) + ",")
    out.append("];")
out.append("")
for (name, dx, dy, c, d, i, names) in tables:
    out.append(f"pub static {name.upper()}: PackedPercentileTable = PackedPercentileTable {{")
    out.append(f"    dim_x: {dx},")
    out.append(f"    dim_y: {dy},")
    out.append(f"    item_count: [{c[0]}, {c[1]}],")
    out.append(f"    difscales: [{d[0]}, {d[1]}],")
    out.append(f"    initial_percs: [{i[0]}, {i[1]}],")
    out.append(f"    items: [&{names[0].upper()}, &{names[1].upper()}],")
    out.append("};")
out.append("")
out.append("/// `get_packed_table` (key `(dim_y << 8) | dim_x`).")
out.append("pub fn get_packed_table(dim_x: u32, dim_y: u32) -> Option<&'static PackedPercentileTable> {")
out.append("    match (dim_y << 8) | dim_x {")
for (name, dx, dy, *_rest) in tables:
    out.append(f"        0x{(dy << 8) | dx:04X} => Some(&{name.upper()}),")
out.append("        _ => None,")
out.append("    }")
out.append("}")
open(os.path.join(ROOT, "src", "astcenc", "percentile_tables.rs"), "w").write("\n".join(out) + "\n")
print(f"{len(arrays)} arrays, {len(tables)} tables")
