#!/usr/bin/env python3
"""Generate src/vk2gl.rs from lib/src/vk2gl.h and its vkFormat2gl*.inl switch bodies,
resolving GL enum names through vk2gl.h and the GL headers it includes."""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx")
vals = {}
for h in ["lib/src/vk2gl.h", "other_include/GL/glcorearb.h", "other_include/GL/glext.h",
          "other_include/GLES2/gl2ext.h"]:
    for name, v in re.findall(r"#define\s+(GL_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b", (ref / h).read_text()):
        vals.setdefault(name, int(v, 0))

out = ["// Generated by scripts/gen_vk2gl.py from lib/src/vk2gl.h and vkFormat2gl*.inl. Do not edit.",
       "//! Port of `vk2gl.h`: VkFormat to OpenGL internal format, format and type (GL loader).",
       "", "use crate::vkformat::VkFormat;", "",
       "/// `GL_INVALID_VALUE`, returned for formats without a GL equivalent.",
       "pub const GL_INVALID_VALUE: u32 = 0x0501;", ""]
for inl, fn, rust in [("vkFormat2glInternalFormat.inl", "vkFormat2glInternalFormat", "vk_format2gl_internal_format"),
                      ("vkFormat2glFormat.inl", "vkFormat2glFormat", "vk_format2gl_format"),
                      ("vkFormat2glType.inl", "vkFormat2glType", "vk_format2gl_type")]:
    arms = []
    for vk, gl in re.findall(r"case\s+VK_FORMAT_(\w+):\s*return\s+(\w+);", (ref / "lib/src" / inl).read_text()):
        arms.append(f"        VkFormat::{vk} => {vals[gl]:#x}, // {gl}")
    assert len(arms) > 50, inl
    out += [f"/// Port of `{fn}`.", f"pub fn {rust}(vk_format: VkFormat) -> u32 {{",
            "    match vk_format {", *arms, "        _ => GL_INVALID_VALUE,", "    }", "}", ""]
Path("src/vk2gl.rs").write_text("\n".join(out))
print("wrote src/vk2gl.rs")
