#!/usr/bin/env python3
"""Generates src/astcenc/sincos_tables.rs: astc-encoder's `prepare_angular_tables` sin / cos
tables as computed by glibc's sinf / cosf (the platform KTX-Software's reference output comes
from). Other libms round some entries differently, so the table is embedded instead of computed
at run time to keep the encoder output identical on every platform. Run on Linux / glibc."""
import ctypes
import os
import platform
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANGULAR_STEPS = 32
SINCOS_STEPS = 64
PI = 3.14159265358979323846

libm = ctypes.CDLL("libm.so.6")
for name in ("sinf", "cosf"):
    getattr(libm, name).restype = ctypes.c_float
    getattr(libm, name).argtypes = [ctypes.c_float]


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def lit(x):
    # The exact f32 bit pattern.
    return f"f32::from_bits(0x{struct.unpack('<I', struct.pack('<f', x))[0]:08x})"


sin_table = [[0.0] * ANGULAR_STEPS for _ in range(SINCOS_STEPS)]
cos_table = [[0.0] * ANGULAR_STEPS for _ in range(SINCOS_STEPS)]
for i in range(ANGULAR_STEPS):
    angle_step = f32(i + 1)
    for j in range(SINCOS_STEPS):
        # (2.0f * astc::PI / (SINCOS_STEPS - 1.0f)) * angle_step * j, rounded like f32.
        a = f32(f32(f32(f32(2.0 * f32(PI)) / f32(SINCOS_STEPS - 1.0)) * angle_step) * f32(j))
        sin_table[j][i] = libm.sinf(a)
        cos_table[j][i] = libm.cosf(a)

out = [
    "// SPDX-FileCopyrightText: 2011-2026 Arm Limited",
    "// SPDX-License-Identifier: Apache-2.0",
    "// Translated to Rust from astc-encoder and modified; see NOTICE.md.",
    "//! Generated by scripts/gen_astcenc_sincos.py with glibc "
    f"{platform.libc_ver()[1]} sinf / cosf; do not edit.",
    "",
]
for name, table in (("SIN_TABLE", sin_table), ("COS_TABLE", cos_table)):
    out.append(f"/// `prepare_angular_tables` `{name.lower()}[SINCOS_STEPS][ANGULAR_STEPS]`.")
    out.append(f"pub const {name}: [[f32; {ANGULAR_STEPS}]; {SINCOS_STEPS}] = [")
    for row in table:
        out.append("    [")
        out.extend(f"        {lit(v)}," for v in row)
        out.append("    ],")
    out.append("];")
    out.append("")

path = os.path.join(ROOT, "src", "astcenc", "sincos_tables.rs")
with open(path, "w") as f:
    f.write("\n".join(out))
