#!/usr/bin/env python3
"""Generate src/cli/formats_gen.rs (VkFormat switch predicates of tools/ktx/formats.h)
and src/cli/validation_messages.rs (tools/ktx/validation_messages.h)."""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx") / "tools/ktx"

NAMES = {
    "getColorModelForBlockCompressedFormat": "get_color_model_for_block_compressed_format",
    "isFormatStencil": "is_format_stencil",
    "isFormatDepth": "is_format_depth",
    "isFormatINT": "is_format_int",
    "isFormatBlockCompressed": "is_format_block_compressed",
    "isFormat3DBlockCompressed": "is_format_3d_block_compressed",
    "isFormatSRGB": "is_format_srgb",
    "isFormatNotSRGBButHasSRGBVariant": "is_format_not_srgb_but_has_srgb_variant",
    "isFormat422": "is_format_422",
    "isFormatAstc": "is_format_astc",
    "isFormatAstcLDR": "is_format_astc_ldr",
}


def rust_str(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def formats():
    src = (ref / "formats.h").read_text()
    out = ["// Generated by scripts/gen_cli_tables.py from tools/ktx/formats.h. Do not edit.", "",
           "use crate::dfd::khr_df::*;", "use crate::vkformat::VkFormat;", ""]
    found = 0
    for m in re.finditer(r"inline (bool|khr_df_model_e) (\w+)\(VkFormat format\) noexcept \{\s*switch \(format\) \{(.*?)\n    \}\n\}", src, re.S):
        ret, cname, body = m.groups()
        body = re.sub(r"//[^\n]*", "", body)
        arms, pending, default = [], [], None
        for tok in re.finditer(r"case (\w+):|default:|return (\w+);", body):
            if tok.group(1):
                pending.append(tok.group(1))
            elif tok.group(0) == "default:":
                pending.append(None)
            else:
                if None in pending:
                    default = tok.group(2)
                    pending = [p for p in pending if p]
                    assert not pending, cname
                else:
                    arms.append((pending, tok.group(2)))
                pending = []
        assert default is not None and arms, cname
        rname = NAMES[cname]
        pats = lambda cs: " | ".join("VkFormat::" + c[len("VK_FORMAT_"):] for c in cs)
        out.append(f"/// Port of `{cname}`.")
        if ret == "bool":
            assert len(arms) == 1 and arms[0][1] == "true" and default == "false", cname
            out += [f"pub fn {rname}(format: VkFormat) -> bool {{", f"    matches!(format, {pats(arms[0][0])})", "}", ""]
        else:
            out += [f"pub fn {rname}(format: VkFormat) -> u32 {{", "    match format {"]
            out += [f"        {pats(cs)} => {v}," for cs, v in arms]
            out += [f"        _ => {default},", "    }", "}", ""]
        found += 1
    assert found == len(NAMES), found
    Path("src/cli/formats_gen.rs").write_text("\n".join(out))


def c_unescape(s):
    return re.sub(r'\\(.)', lambda m: {"n": "\n", "t": "\t", "r": "\r"}.get(m.group(1), m.group(1)), s)


def messages():
    src = (ref / "validation_messages.h").read_text()
    src = re.sub(r"^\s*//[^\n]*", "", src, flags=re.M)
    out = ["// Generated by scripts/gen_cli_tables.py from tools/ktx/validation_messages.h. Do not edit.",
           "#![allow(non_upper_case_globals)]", "", "use super::validate::{Issue, IssueType};", ""]
    count = 0
    for sm in re.finditer(r"\nstruct (\w+) \{(.*?)\n\};", src, re.S):
        sname, body = sm.groups()
        if sname.startswith("Issue"):
            continue
        out += [f"/// Port of `ktx::{sname}`.", f"pub struct {sname};", "", f"impl {sname} {{"]
        for im in re.finditer(r"static constexpr Issue(Warning|Error|Fatal) (\w+)\{\s*(\d+),(.*?)\};", body, re.S):
            kind, name, ident, rest = im.groups()
            groups = re.findall(r'((?:"(?:[^"\\]|\\.)*"\s*)+)', rest)
            strs = ["".join(c_unescape(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', g)) for g in groups]
            assert len(strs) == 2, (name, strs)
            out += [f"    pub const {name}: Issue = Issue {{",
                    f"        type_: IssueType::{kind},",
                    f"        id: {ident},",
                    f"        message: {rust_str(strs[0])},",
                    f"        details_fmt: {rust_str(strs[1])},",
                    "    };"]
            count += 1
        out += ["}", ""]
    assert count > 150, count
    Path("src/cli/validation_messages.rs").write_text("\n".join(out))
    print(f"{count} issues")


formats()
messages()
print("wrote src/cli/formats_gen.rs, src/cli/validation_messages.rs")
