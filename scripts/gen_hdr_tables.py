#!/usr/bin/env python3
"""Generate src/basisu/hdr_tables.rs: ASTC ISE decode tables (basisu_astc_helpers.h)
and BC6H tables (basisu_transcoder.cpp), extracted verbatim."""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx") / "external/basis_universal/transcoder"
helpers = (ref / "basisu_astc_helpers.h").read_text()
cpp = (ref / "basisu_transcoder.cpp").read_text()


def body_of(src, cname):
    m = re.search(r"\b" + re.escape(cname) + r"\s*(\[[^\]]*\])+\s*=\s*(//[^\n]*)?\s*\{", src)
    assert m, cname
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1 : j]
    raise AssertionError(cname)


def tokens(body):
    body = re.sub(r"//[^\n]*", "", body)
    return re.findall(r"0x[0-9a-fA-F]+|-?\d+", body)


def top_groups(body):
    body = re.sub(r"//[^\n]*", "", body)
    groups, depth, start = [], 0, 0
    for j, ch in enumerate(body):
        if ch == "{":
            if depth == 0:
                start = j + 1
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                groups.append(body[start:j])
    return groups


def rows(body, width):
    out = []
    for g in re.findall(r"\{([^{}]*)\}", body):
        v = [str(int(t, 0)) for t in tokens(g)]
        assert len(v) == width, g
        out.append("[" + ", ".join(v) + "]")
    return out


out = ["// Generated by scripts/gen_hdr_tables.py from basisu_astc_helpers.h and", "// basisu_transcoder.cpp. Do not edit.", ""]

r = rows(body_of(helpers, "s_trit_decode"), 5)
out.append(f"pub const TRIT_DECODE: [[u8; 5]; {len(r)}] = [{', '.join(r)}];\n")
r = rows(body_of(helpers, "s_quint_decode"), 3)
out.append(f"pub const QUINT_DECODE: [[u8; 3]; {len(r)}] = [{', '.join(r)}];\n")
r = rows(body_of(cpp, "g_bc6h_mode_sig_bits"), 4)
out.append(f"pub const BC6H_MODE_SIG_BITS: [[u8; 4]; {len(r)}] = [{', '.join(r)}];\n")

layouts = []
for mode in top_groups(body_of(cpp, "g_bc6h_bit_layouts")):
    entries = rows(mode, 4)
    assert len(entries) <= 25
    entries += ["[-1, 0, 0, 0]"] * (25 - len(entries))
    layouts.append("[" + ", ".join(entries) + "]")
out.append(f"pub const BC6H_BIT_LAYOUTS: [[[i8; 4]; 25]; {len(layouts)}] = [{', '.join(layouts)}];\n")

pats = []
for pat in top_groups(body_of(cpp, "g_bc6h_2subset_patterns")):
    v = [str(int(t, 0)) for t in tokens(pat)]
    assert len(v) == 16
    pats.append("[" + ", ".join(v) + "]")
out.append(f"pub const BC6H_2SUBSET_PATTERNS: [[u8; 16]; {len(pats)}] = [{', '.join(pats)}];\n")

Path("src/basisu/hdr_tables.rs").write_text("\n".join(out))
print("wrote src/basisu/hdr_tables.rs")
