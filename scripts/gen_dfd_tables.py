#!/usr/bin/env python3
"""Translate KTX-Software dfdutils vk2dfd.inl and dfd2vk.inl into Rust.

Writes src/dfd/vk2dfd.rs and src/dfd/dfd2vk.rs. The C sources use a small,
regular subset of C which is converted with targeted rewrites.
"""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx") / "external/dfdutils"

SUFFIX = {"s_UNORM": "Unorm", "s_SNORM": "Snorm", "s_USCALED": "Uscaled", "s_SSCALED": "Sscaled",
          "s_UINT": "Uint", "s_SINT": "Sint", "s_SFLOAT": "Sfloat", "s_UFLOAT": "Ufloat",
          "s_SRGB": "Srgb", "s_SFIXED5": "Sfixed5"}
COMP = {"c_BC1_RGB": "Bc1Rgb", "c_BC1_RGBA": "Bc1Rgba", "c_BC2": "Bc2", "c_BC3": "Bc3", "c_BC4": "Bc4",
        "c_BC5": "Bc5", "c_BC6H": "Bc6h", "c_BC7": "Bc7", "c_ETC2_R8G8B8": "Etc2R8G8B8",
        "c_ETC2_R8G8B8A1": "Etc2R8G8B8A1", "c_ETC2_R8G8B8A8": "Etc2R8G8B8A8", "c_EAC_R11": "EacR11",
        "c_EAC_R11G11": "EacR11G11", "c_ASTC": "Astc", "c_ETC1S": "Etc1s", "c_PVRTC": "Pvrtc",
        "c_PVRTC2": "Pvrtc2"}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


KNOWN = set(re.findall(r"(VK_FORMAT_\w+)\s*=", (ref.parent.parent / "lib/src/vkformat_enum.h").read_text()))


def vk(name):
    # dfd2vk.inl uses Vulkan-header alias names (e.g. *_SFLOAT_BLOCK_EXT) for core formats.
    if name not in KNOWN:
        for suffix in ("_EXT", "_KHR"):
            if name.endswith(suffix) and name[: -len(suffix)] in KNOWN:
                name = name[: -len(suffix)]
                break
        else:
            sys.exit(f"unknown format {name}")
    return "VkFormat::" + name[len("VK_FORMAT_"):]


# ---------------------------------------------------------------- vk2dfd
def b(a):
    return "true" if a.strip() not in ("0",) else "false"


def gen_vk2dfd():
    src = strip_comments((ref / "vk2dfd.inl").read_text())
    cases = re.split(r"\ncase (VK_FORMAT_\w+):", "\n" + src)
    arms = []
    for i in range(1, len(cases), 2):
        name, body = cases[i], cases[i + 1].strip()
        body = body.strip()
        if body.startswith("{"):
            body = body[1:body.rstrip().rfind("}")]
        stmts = []
        for decl in re.finditer(r"int (\w+)\[\] = \{([^}]*)\};", body):
            vals = ", ".join(v.strip() for v in decl.group(2).split(","))
            stmts.append(f"let {decl.group(1)}: &[u32] = &[{vals}];")
        call = re.search(r"return (createDFD\w+)\((.*?)\);", body, re.S)
        fn, args = call.group(1), [a.strip() for a in call.group(2).split(",")]
        snake = {"shiftBits": "shift_bits", "position_xs": "position_xs", "position_ys": "position_ys"}
        stmts = [re.sub(r"\bshiftBits\b", "shift_bits", x) for x in stmts]
        args = [snake.get(a, a) for a in args]

        def suf(a):
            return "VkSuffix::" + SUFFIX[a]

        if fn == "createDFDUnpacked":
            expr = f"create_dfd_unpacked({b(args[0])}, {args[1]}, {args[2]}, {b(args[3])}, {suf(args[4])})"
        elif fn == "createDFDPacked":
            expr = f"create_dfd_packed({b(args[0])}, {args[1]}, {args[2]}, {args[3]}, {suf(args[4])})"
        elif fn == "createDFDPackedShifted":
            expr = (f"create_dfd_packed_shifted({b(args[0])}, {args[1]}, {args[2]}, {args[3]}, "
                    f"{args[4]}, {suf(args[5])})")
        elif fn == "createDFD422":
            expr = (f"create_dfd_422({b(args[0])}, {args[1]}, {args[2]}, {args[3]}, {args[4]}, "
                    f"{args[5]}, {args[6]}, {suf(args[7])})")
        elif fn == "createDFDCompressed":
            expr = (f"create_dfd_compressed(VkCompScheme::{COMP[args[0]]}, {args[1]}, {args[2]}, "
                    f"{args[3]}, {suf(args[4])})")
        elif fn == "createDFDDepthStencil":
            expr = f"create_dfd_depth_stencil({args[0]}, {args[1]}, {args[2]})"
        elif fn == "createDFDAlpha":
            expr = f"create_dfd_alpha({b(args[0])}, {args[1]}, {suf(args[2])})"
        else:
            sys.exit(f"unknown {fn}")
        if stmts:
            arms.append(f"        {vk(name)} => {{\n" + "".join(f"            {s}\n" for s in stmts)
                        + f"            {expr}\n        }}")
        else:
            arms.append(f"        {vk(name)} => {expr},")
    out = ["// @generated by scripts/gen_dfd_tables.py from dfdutils/vk2dfd.inl. Do not edit.",
           "//! Port of `vk2dfd`.", "",
           "use super::createdfd::*;", "use super::{VkCompScheme, VkSuffix};", "use crate::vkformat::VkFormat;", "",
           "/// Port of `vk2dfd`: create the DFD for `format`. `None` for unsupported formats.",
           "#[allow(clippy::identity_op)]",
           "pub fn vk2dfd(format: VkFormat) -> Option<Vec<u32>> {",
           "    match format {"]
    out += arms
    out += ["        _ => None,", "    }", "}", ""]
    Path("src/dfd/vk2dfd.rs").write_text("\n".join(out))
    print(f"vk2dfd: {len(arms)} formats")


# ---------------------------------------------------------------- dfd2vk
def find_paren(s, i):
    """s[i] == '('; return index after matching ')'."""
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "(":
            depth += 1
        elif s[j] == ")":
            depth -= 1
            if depth == 0:
                return j + 1
    raise ValueError("unbalanced")


def conv_cond(c):
    # bit tests used as booleans -> explicit != 0
    c = re.sub(r"\br & (i_\w+)", lambda m: f"(r & {m.group(1).upper()}) != 0", c)
    c = re.sub(r"\((dfdsval\([^()]*\)) & (KHR_DF_SAMPLE_DATATYPE_\w+)\) > 0", r"(\1 & \2) != 0", c)
    c = re.sub(r"!\((dfdsval\([^()]*\)) & (KHR_DF_SAMPLE_DATATYPE_\w+)\)", r"(\1 & \2) == 0", c)
    return c


def wrap_stmt(s, i):
    """Wrap a single statement starting at s[i] (no brace) up to ';'."""
    j = s.index(";", i)
    return "{ " + s[i:j + 1].strip() + " }", j + 1


def convert_ifs(s):
    out = []
    i = 0
    while i < len(s):
        m = re.compile(r"\b(if|else)\b").search(s, i)
        if not m:
            out.append(s[i:])
            break
        out.append(s[i:m.start()])
        if m.group(1) == "if":
            p = s.index("(", m.end())
            e = find_paren(s, p)
            cond = conv_cond(s[p + 1:e - 1].strip())
            out.append(f"if {cond} ")
            k = e
        else:
            out.append("else ")
            k = m.end()
        # next token
        n = k
        while n < len(s) and s[n].isspace():
            n += 1
        if s.startswith("{", n) or re.match(r"if\b", s[n:]):
            i = n
        else:
            stmt, i = wrap_stmt(s, n)
            out.append(stmt)
    return "".join(out)


def gen_dfd2vk():
    src = strip_comments((ref / "dfd2vk.inl").read_text())
    # Drop declarations/defines handled in the Rust prologue.
    src = re.sub(r"^\s*(enum InterpretDFDResult r;|InterpretedDFDChannel \w+ = \{0,0\};|#define \w+ \w+|uint32_t wordBytes;|const uint32_t \*bdb = dfd \+ 1;)\s*$",
                 "", src, flags=re.M)
    for a, b in (("Y1", "R"), ("Y2", "A"), ("CB", "G"), ("U", "G"), ("CR", "B"), ("V", "B")):
        src = re.sub(rf"\b{a}\.", f"{b}.", src)
    src = src.replace("r = interpretDFD(dfd, &R, &G, &B, &A, &wordBytes);",
                      "let r = interpret_dfd(dfd, &mut R, &mut G, &mut B, &mut A, &mut wordBytes);")
    src = re.sub(r"KHR_DFDVAL\(\(?(?:dfd \+ 1|bdb)\)?, (\w+)\)", r"dfdval(bdb, \1)", src)
    src = re.sub(r"KHR_DFDSVAL\(\(?(?:dfd \+ 1|bdb)\)?, (\w+), (\w+)\)", r"dfdsval(bdb, \1, \2)", src)
    src = re.sub(r"KHR_DFDSAMPLECOUNT\(\(?(?:dfd \+ 1|bdb)\)?\)", r"dfdsamplecount(bdb)", src)
    src = re.sub(r"return\s+(VK_FORMAT_\w+);", lambda m: f"return {vk(m.group(1))};", src)
    src = re.sub(r"\bwordBytes\b", "word_bytes", src)
    # switch -> match
    sw = src.index("switch (")
    e = find_paren(src, src.index("(", sw))
    scrut = src[src.index("(", sw) + 1:e - 1]
    body_start = src.index("{", e)
    depth, j = 0, body_start
    while True:
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = src[body_start + 1:j]
    parts = re.split(r"\n\s*(case (\w+):|default:)", body)
    arms = []
    k = 1
    while k < len(parts):
        label, code = parts[k + 1], parts[k + 2]
        code = re.sub(r"\bbreak;", "", code).strip().rstrip(";").strip()
        pat = label if label else "_"
        arms.append(f"{pat} => {{\n{code}\n}}")
        k += 3
    match = f"match {scrut} {{\n" + "\n".join(arms) + "\n}"
    src = src[:sw] + match + src[j + 1:]
    src = convert_ifs(src)
    src = src.replace("r & word_bytes", "r & word_bytes")
    body = src.strip()
    body = re.sub(r"return VkFormat::UNDEFINED;\s*$", "", body)
    out = ["// @generated by scripts/gen_dfd_tables.py from dfdutils/dfd2vk.inl. Do not edit.",
           "//! Port of `dfd2vk`.", "#![allow(non_snake_case, unused_parens, clippy::collapsible_else_if, clippy::needless_return, clippy::nonminimal_bool, clippy::needless_else, clippy::if_same_then_else)]", "",
           "use super::access::*;", "use super::interpret::*;", "use super::khr_df::*;",
           "use crate::vkformat::VkFormat;", "",
           "/// Port of `dfd2vk`: find the VkFormat described by `dfd` (whole descriptor).",
           "/// Returns `VkFormat::UNDEFINED` when there is no match.",
           "pub fn dfd2vk(dfd: &[u32]) -> VkFormat {",
           "    let bdb = bdb(dfd);",
           "    let mut R = InterpretedDfdChannel::default();",
           "    let mut G = InterpretedDfdChannel::default();",
           "    let mut B = InterpretedDfdChannel::default();",
           "    let mut A = InterpretedDfdChannel::default();",
           "    let mut word_bytes: u32 = 0;",
           body,
           "    VkFormat::UNDEFINED",
           "}", ""]
    Path("src/dfd/dfd2vk.rs").write_text("\n".join(out))
    print("dfd2vk: written")


gen_vk2dfd()
gen_dfd2vk()
