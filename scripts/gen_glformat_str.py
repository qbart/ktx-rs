#!/usr/bin/env python3
"""Generate src/glformat_str.rs from lib/src/glformat_str.c, resolving GL enum
names through the GL headers the C file includes."""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx")
src = (ref / "lib/src/glformat_str.c").read_text()
vals = {"GL_LUMINANCE": 0x1909, "GL_LUMINANCE_ALPHA": 0x190A}
for h in ["other_include/GL/glcorearb.h", "other_include/GL/glext.h", "other_include/GLES2/gl2ext.h"]:
    for name, v in re.findall(r"#define\s+(GL_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b", (ref / h).read_text()):
        vals.setdefault(name, int(v, 0))
vals["GL_SR8"] = vals["GL_SR8_EXT"]
vals["GL_SRG8"] = vals["GL_SRG8_EXT"]

out = ["// Generated by scripts/gen_glformat_str.py from lib/src/glformat_str.c. Do not edit.", "",
       "use std::borrow::Cow;", "", "use crate::strings::c_hash_x as hash_x;", ""]
for fn, rust in [("glFormatString", "gl_format_string"), ("glInternalformatString", "gl_internalformat_string"),
                 ("glTypeString", "gl_type_string")]:
    m = re.search(r"const char\* " + fn + r"\(GLenum \w+\)\s*\{(.*?)\n\}", src, re.S)
    assert m, fn
    arms, seen = [], set()
    for case, name in re.findall(r"case\s+(\w+):\s*return\s+\"([^\"]*)\";", m.group(1)):
        v = int(case, 0) if case[0].isdigit() else vals[case]
        assert v not in seen, (fn, case)
        seen.add(v)
        arms.append(f"        {v:#x} => Cow::Borrowed(\"{name}\"),")
    assert len(arms) > 3, fn
    out += [f"/// Port of `{fn}`: unknown values print as C `%#x`.",
            f"pub fn {rust}(value: u32) -> Cow<'static, str> {{",
            "    match value {", *arms, "        _ => Cow::Owned(hash_x(value)),", "    }", "}", ""]
Path("src/glformat_str.rs").write_text("\n".join(out))
print("wrote src/glformat_str.rs")
