#!/usr/bin/env python3
"""Generate src/dfd/khr_df.rs constants from KTX-Software external/dfdutils/KHR/khr_df.h."""
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1] if len(sys.argv) > 1 else "ref/ktx")
src = (ref / "external/dfdutils/KHR/khr_df.h").read_text()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
out = Path("src/dfd/khr_df.rs")

L = ["// @generated by scripts/gen_khr_df.py from KTX-Software KHR/khr_df.h. Do not edit.",
     "//! Port of `khr_df.h` enumerants. All values are `u32`.",
     "#![allow(non_upper_case_globals)]", ""]
values = {}
for em in re.finditer(r"typedef enum (\w+)\s*\{(.*?)\}\s*(\w+);", src, re.S):
    body, tname = em.group(2), em.group(3)
    L.append(f"// {tname}")
    for m in re.finditer(r"(KHR_DF_\w+)\s*=\s*([^,\n]+)", body):
        name, expr = m.group(1), m.group(2).strip()
        expr = expr.replace("(int)", "").strip()
        expr = re.sub(r"(0x[0-9A-Fa-f]+|\d+)U\b", r"\1", expr)
        if re.fullmatch(r"KHR_DF_\w+", expr):
            val = values[expr]
        else:
            val = eval(expr.replace("<<", "<<"), {}, {})
        values[name] = val
        L.append(f"pub const {name}: u32 = {val:#x};")
    L.append("")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L))
print(f"wrote {out}: {len(values)} constants")
