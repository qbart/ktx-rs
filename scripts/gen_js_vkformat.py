#!/usr/bin/env python3
"""Generates bindings/js/src/vk_format.rs (the `VkFormat` enum of libktx.js) from
./ref/ktx/interface/js_binding/vk_format.inl, keeping its names and order."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "ktx", "interface", "js_binding", "vk_format.inl")

with open(SRC) as f:
    names = re.findall(r'\.value\("(\w+)",\s*VK_FORMAT_(\w+)\)', f.read())

out = [
    "// SPDX-FileCopyrightText: 2015-2024 The Khronos Group Inc.",
    "// SPDX-License-Identifier: Apache-2.0",
    "// Part of the Rust port of KTX-Software; see NOTICE.md.",
    "//! Generated by scripts/gen_js_vkformat.py from interface/js_binding/vk_format.inl; do not",
    "//! edit.",
    "",
    "use ktx::vkformat::VkFormat;",
    "",
    "/// `enum_<VkFormat>(\"VkFormat\")` values.",
    "pub const VK_FORMATS: &[(&str, u32)] = &[",
]
for js, c in names:
    assert js == c, (js, c)
    out.append(f'    ("{js}", VkFormat::{c}.0),')
out.append("];")
with open(os.path.join(ROOT, "bindings", "js", "src", "vk_format.rs"), "w") as f:
    f.write("\n".join(out) + "\n")
print(len(names))
